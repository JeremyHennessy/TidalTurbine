'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'site/index.html'),'utf8');
const code=fs.readFileSync(path.join(root,'site/app.js'),'utf8');
const artworkCode=fs.readFileSync(path.join(root,'site/artwork.js'),'utf8');
for(const id of ['comparison-grid','compare-select','rm2-tradeoff','rm2-share','rm1-plot','rm1-rotor-filter','force-cells','force-window','rm2-speed-bars','rm2-speed-sweep','rm2-raw-chart','rm2-raw-speed','rm2-raw-metric']){
  assert.ok(html.includes('id="'+id+'"'),'missing DOM target '+id);
}
const elements=new Map();
const element=(selector)=>{
  if(!elements.has(selector))elements.set(selector,{innerHTML:'',textContent:'',value:selector==='#rm2-share'?'0.95':selector==='#rm1-rotor-filter'?'both':selector==='#force-window'?'full':'',addEventListener(){},querySelectorAll(){return []},classList:{toggle(){},remove(){},add(){}},setAttribute(){}});
  return elements.get(selector);
};
const document={querySelector:element,querySelectorAll:()=>[],addEventListener(){}};
const ctx=vm.createContext({document,console,window:{},location:{},history:{},setTimeout,Math,Number,JSON});
new vm.Script(artworkCode,{filename:'site/artwork.js'}).runInContext(ctx);
new vm.Script(code,{filename:'site/app.js'}).runInContext(ctx);
ctx.registry=JSON.parse(fs.readFileSync(path.join(root,'research/mechanisms.json'),'utf8'));
vm.runInContext('applyMechanisms(registry);renderDesign()',ctx);
assert.match(element('#design-title').textContent,/Seabed horizontal-axis turbine/,'initial selection should render the main studio');
assert.match(element('#design-viewport').innerHTML,/NOT TO SCALE/,'main studio illustration should initialize');

const expectedDesigns=['seabed','floating','counter','rim','crossflow','helical','savonius','foil','screw','kite','duct','pressure','eel','viv'];
const rendered=vm.runInContext("Object.keys(DESIGNS).map(key=>({key,svg:designSvg(key,true),thumb:window.TidalArtwork.thumbnail(key)}))",ctx);
assert.equal(rendered.length,14,'all fourteen canonical mechanism drawings must be upgraded');
assert.deepEqual(Array.from(rendered,x=>x.key).sort(),expectedDesigns.slice().sort());
const uniqueScenes=new Set();
for(const item of rendered){
  assert.match(item.svg,/class="tidal-artwork tidal-artwork-/,'selected studio and comparisons use the new vector engine');
  assert.match(item.svg,/role="img"/,'large technical drawings have text alternatives');
  assert.match(item.svg,/TECHNICAL CONCEPT/,'consistent scientific visual header');
  assert.match(item.svg,/SCHEMATIC GEOMETRY/,'drawing must not imply calibrated geometry');
  assert.match(item.svg,/class="art-annotation"/,'all fourteen scenes require specific component labels');
  assert.match(item.thumb,/aria-hidden="true"/,'selection thumbnails do not duplicate accessible text');
  assert.ok(item.svg.length>3400,'complete component scene expected for '+item.key);
  assert.ok(!item.svg.includes('undefined')&&!item.svg.includes('NaN'),'no broken rendered numbers for '+item.key);
  assert.ok(!item.svg.includes('&nbsp;'),'exported standalone SVG must contain only XML-supported entities');
  uniqueScenes.add(item.svg.replace(/tidal-artwork-[a-z]+/g,'tidal-artwork-KEY'));
}
assert.equal(uniqueScenes.size,14,'every concept must have distinct mechanical artwork');
vm.runInContext('setupDesign()',ctx);
const selectorHTML=element('#design-selector').innerHTML;
assert.equal((selectorHTML.match(/class="design-choice-preview"/g)||[]).length,14,'all options show a concept image thumbnail');
assert.equal((selectorHTML.match(/aria-pressed="(?:true|false)"/g)||[]).length,14,'each selection exposes pressed state');
const noLabels=vm.runInContext("window.TidalArtwork.render('crossflow',{annotations:false,large:true})",ctx);
assert.ok(!noLabels.includes('class="art-annotation"'),'annotation toggle removes overlays rather than hiding components');
const yesLabels=vm.runInContext("window.TidalArtwork.render('crossflow',{annotations:true,large:true})",ctx);
assert.match(yesLabels,/class="art-annotation"/,'annotation overlay restores technical callouts');
assert.match(html,/id="download-design-svg"/,'new stand-alone vector export control must be present');
assert.ok(html.indexOf('artwork.js')<html.indexOf('app.js'),'vector definitions must load before app initialization');

vm.runInContext('renderComparison()',ctx);
assert.match(element('#comparison-grid').innerHTML,/Seabed horizontal-axis turbine/);
assert.match(element('#comparison-grid').innerHTML,/Cross-flow vertical-axis turbine/);
assert.match(element('#comparison-grid').innerHTML,/Source record/);
assert.equal(element('#compare-select').value,'crossflow');
vm.runInContext("selected='crossflow';renderComparison()",ctx);
assert.equal(element('#compare-select').value,'seabed','same design cannot compare to itself');
assert.match(element('#comparison-grid').innerHTML,/SEABED/i);
vm.runInContext("selected='foil';renderComparison()",ctx);
assert.match(element('#comparison-grid').innerHTML,/Heaving\/pitching oscillating hydrofoil/i);
ctx.drag=JSON.parse(fs.readFileSync(path.join(root,'reports/RM2-TRADEOFF-001.json'),'utf8'));
vm.runInContext('rm2Tradeoff=drag;renderRM2Tradeoff()',ctx);
assert.match(element('#rm2-tradeoff').innerHTML,/Alternative run 10/);
assert.match(element('#rm2-tradeoff').innerHTML,/5.51%/);
assert.match(element('#rm2-tradeoff').innerHTML,/not establish smaller damaging cyclic loads/);
element('#rm2-share').value='0.90';
vm.runInContext('renderRM2Tradeoff()',ctx);
assert.match(element('#rm2-tradeoff').innerHTML,/Alternative run 9/);
element('#rm2-share').value='0.99';
vm.runInContext('renderRM2Tradeoff()',ctx);
assert.match(element('#rm2-tradeoff').innerHTML,/Alternative run 11/);
vm.runInContext('rm2Tradeoff=null;renderRM2Tradeoff()',ctx);
assert.match(element('#rm2-tradeoff').innerHTML,/unavailable/);


ctx.crossFixture=JSON.parse(fs.readFileSync(path.join(root,'reports/RM2-CROSSSPEED-001.json'),'utf8'));
element('#rm2-speed-sweep').value='both';
vm.runInContext('rm2CrossSpeed=crossFixture;renderRM2CrossSpeed()',ctx);
assert.equal((element('#rm2-speed-bars').innerHTML.match(/class="speed-bar-row"/g)||[]).length,20,'two coefficients × ten published source series');
assert.match(element('#rm2-speed-bars').innerHTML,/29\.86%/,'observed slow-speed Cp penalty should be visible');
assert.match(element('#rm2-speed-bars').innerHTML,/NOT MEASURED/,'physical fatigue remains unknown');
element('#rm2-speed-sweep').value='A';
vm.runInContext('renderRM2CrossSpeed()',ctx);
assert.equal((element('#rm2-speed-bars').innerHTML.match(/class="speed-bar-row"/g)||[]).length,10,'five first-sweep rows for each coefficient');
element('#rm2-speed-sweep').value='B';
vm.runInContext('renderRM2CrossSpeed()',ctx);
assert.match(element('#rm2-speed-bars').innerHTML,/Sweep B/,'second source sweep should be interactive');
assert.ok(!element('#rm2-speed-bars').innerHTML.includes('Sweep A'),'A entries hidden on B selection');
vm.runInContext('rm2CrossSpeed=null;renderRM2CrossSpeed()',ctx);
assert.match(element('#rm2-speed-bars').innerHTML,/unavailable/,'no false new source data');

ctx.rawNI=JSON.parse(fs.readFileSync(path.join(root,'reports/RM2-RAW-LOADS-001.json'),'utf8'));
element('#rm2-raw-speed').value='1.0';
element('#rm2-raw-metric').value='drag';
vm.runInContext('rm2RawRig=rawNI;renderRM2RawRig()',ctx);
assert.equal((element('#rm2-raw-chart').innerHTML.match(/<polyline /g)||[]).length,2,'two original NI rotor-phase traces');
assert.match(element('#rm2-raw-chart').innerHTML,/-4\.68%/,'raw measured drag p95 change');
assert.match(element('#rm2-raw-chart').innerHTML,/NOT EVALUABLE/,'rig support loads are not fatigue');
element('#rm2-raw-metric').value='torque';
vm.runInContext('renderRM2RawRig()',ctx);
assert.match(element('#rm2-raw-chart').innerHTML,/\+1\.71%/,'1m/s shaft-torque variation increased');
element('#rm2-raw-speed').value='0.4';
vm.runInContext('renderRM2RawRig()',ctx);
assert.match(element('#rm2-raw-chart').innerHTML,/0\.4 metres per second/,'0.4m/s original NI test selected');
vm.runInContext('rm2RawRig=null;renderRM2RawRig()',ctx);
assert.match(element('#rm2-raw-chart').innerHTML,/unavailable/,'raw source missing should be explicit');
assert.match(html,/NO BLADE STRESS DATA/,'never label original NI rig drag as blade bending');

ctx.rm1Fixture=JSON.parse(fs.readFileSync(path.join(root,'reports/RM1-OBS-001.json'),'utf8'));
vm.runInContext('rm1=rm1Fixture;rm1Plot()',ctx);
assert.match(element('#rm1-plot').innerHTML,/0\.477/,'source-published right peak should appear');
assert.match(element('#rm1-plot').innerHTML,/0\.412/,'source-published left peak should appear');
assert.equal((element('#rm1-plot').innerHTML.match(/<circle /g)||[]).length,32,'plot every published table point');
assert.ok(!element('#rm1-plot').innerHTML.includes('<polyline'),'do not invent an interpolated performance curve');
element('#rm1-rotor-filter').value='right';
vm.runInContext('rm1Plot()',ctx);
assert.equal((element('#rm1-plot').innerHTML.match(/<circle /g)||[]).length,16,'filter to right rotor');
element('#rm1-rotor-filter').value='left';
vm.runInContext('rm1Plot()',ctx);
assert.equal((element('#rm1-plot').innerHTML.match(/<circle /g)||[]).length,16,'filter to left rotor');
vm.runInContext('rm1=null;rm1Plot()',ctx);
assert.match(element('#rm1-plot').innerHTML,/unavailable/,'do not fabricate unavailable RM1 points');

ctx.forceFixture=JSON.parse(fs.readFileSync(path.join(root,'reports/FORCE-CAMPAIGN-QA-001.json'),'utf8'));
vm.runInContext('forceCampaign=forceFixture;renderForceCampaign()',ctx);
assert.equal((element('#force-cells').innerHTML.match(/class='force-cell'/g)||[]).length,50,'plot 50 actual range cells');
assert.match(element('#force-campaign-metrics').innerHTML,/263,250/);
assert.match(element('#force-campaign-metrics').innerHTML,/97,911/);
assert.match(element('#force-cell-detail').innerHTML,/1,210 \/ 5,265 exact-zero triples/,'correct 29.5 m full-campaign count');
assert.match(element('#force-cell-detail').innerHTML,/Not scientifically qualified/);
element('#force-window').value='screen';
vm.runInContext('renderForceCampaign()',ctx);
assert.match(element('#force-cell-detail').innerHTML,/1,120 \/ 5,175 exact-zero triples/,'pressure-screened subset must use different counts');
assert.match(element('#force-window-caption').textContent,/NOT a manufacturer QC rule/);
vm.runInContext('forceSelectedRange=1.5;renderForceCampaign()',ctx);
assert.match(element('#force-cell-detail').innerHTML,/0 \/ 5,175 exact-zero triples/);
assert.match(element('#force-cell-detail').innerHTML,/Not scientifically qualified/,'a numeric-zero-free cell is still not QC-approved');
vm.runInContext('forceCampaign=null;renderForceCampaign()',ctx);
assert.match(element('#force-cells').innerHTML,/unavailable/,'do not display implied measured quality without report');

assert.match(html,/97,911/,'FORCE exact-zero observation count must remain');
assert.match(html,/263,250/,'FORCE complete processed-record count must remain');
assert.match(html,/no FORCE observations enter energy modelling/,'do not use unqualified FORCE currents');
assert.match(html,/FORCE-CAMPAIGN-QA-001\.json/,'full processed-campaign QA report should be linked');
assert.ok(!html.includes('Data acquisition pending'),'stale FORCE acquisition status');
console.log('TidalLab UI smoke passed: all 14 distinct accessible design scenes, thumbnail selector, illustration/annotation controls, RM1/RM2 data and FORCE QA.');
